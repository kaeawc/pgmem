#!/usr/bin/env python3
"""Regenerates PARITY.md from parity/go_tests.tsv."""
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
rows = [l.split("\t") for l in open(os.path.join(ROOT, "parity/go_tests.tsv")).read().splitlines()[1:] if l.strip()]
dev = [r for r in rows if r[4] == "deviation"]
done = sum(1 for r in rows if r[4] in ("ported", "deviation"))
out = [
    "# Parity with pgmem-go",
    "",
    "Every test in the pgmem-go suite has a Rust counterpart. `parity/go_tests.tsv` maps each Go test",
    "(package, file, name) to the Rust test that ports it and records its status;",
    "`scripts/parity.py check` (CI job `parity`) verifies every listed Rust test exists.",
    "This file is generated by `scripts/parity_doc.py`.",
    "",
    f"**Status: {done}/{len(rows)} Go tests ported** ({done - len(dev)} with identical assertions, {len(dev)} deviations).",
    "",
    "How the port was verified: the 515 integration-level tests (pgmem-go's `postgres/`, `examples/` and",
    "`exec/` packages) run as Rust integration tests in `crates/pgmem/tests/it/`, driven by a real",
    "Postgres client (tokio-postgres). The same tests also run against real PostgreSQL 18 (CI job",
    "`postgres-fidelity`), and every assertion holds there too. Unit tests of Go-internal packages",
    "(`types`, `storage`, `postgres/parse`) are ported into the corresponding crates.",
    "",
    "Where a Go test only checked that *an* error occurred, the Rust test usually also asserts the",
    "SQLSTATE and message real Postgres produces.",
    "",
    "## Deviations from pgmem-go",
    "",
    "pgmem-go approximated Postgres in places (no `numeric`, `date`, `timestamp` or `time` types; raw,",
    "unnormalized jsonb; table-level write-conflict detection; ...). Where its tests encoded such an",
    "approximation, the Rust port asserts what PostgreSQL actually does:",
    "",
    "| Go test | What changed |",
    "|---|---|",
]
for r in dev:
    note = r[5].replace("|", "\\|")
    out.append(f"| `{r[0]}/{r[1]}` `{r[2]}` | {note} |")
out += [
    "",
    "Behavioural changes beyond the Go tests' scope (all toward Postgres fidelity):",
    "",
    "- No bootstrap `users` table: a new server starts empty, like a fresh Postgres database.",
    "- DDL is transactional (`CREATE TABLE` inside a rolled-back transaction disappears).",
    "- READ COMMITTED sees other transactions' commits at each statement; REPEATABLE READ and",
    "  SERIALIZABLE keep one snapshot. Write conflicts are detected per row, not per table.",
    "- An UPDATE gives the row a new physical position, so unordered scans return updated rows last,",
    "  as Postgres heaps do.",
    "- `now()` is the transaction start time; `server_version` reports 18.0.",
    "- Errors carry Postgres' SQLSTATE, DETAIL and schema/table/column/constraint fields.",
    "",
]
open(os.path.join(ROOT, "PARITY.md"), "w").write("\n".join(out))
print(f"PARITY.md: {done}/{len(rows)}, {len(dev)} deviations")
