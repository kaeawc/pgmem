-- psql's describe commands over a small schema.
CREATE TYPE status AS ENUM ('open', 'closed');
CREATE DOMAIN positive AS int CHECK (VALUE > 0);
CREATE TABLE customers (
  id int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name text NOT NULL,
  email varchar(80) UNIQUE,
  score positive DEFAULT 10,
  state status NOT NULL DEFAULT 'open'
);
CREATE TABLE orders (
  id serial PRIMARY KEY,
  customer_id int NOT NULL REFERENCES customers (id) ON DELETE CASCADE,
  total numeric(10,2) CHECK (total >= 0),
  placed_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX orders_customer_idx ON orders (customer_id);
CREATE VIEW big_orders AS SELECT id, total FROM orders WHERE total > 100;
CREATE SEQUENCE invoice_seq START 1000;
CREATE SCHEMA reporting;
CREATE TABLE reporting.daily (day date PRIMARY KEY, n int);
COMMENT ON TABLE customers IS 'People who buy things';
