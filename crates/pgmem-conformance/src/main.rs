//! `pgmem-conformance`: runs the SQL corpus in `conformance/`.
//!
//! ```text
//! pgmem-conformance                         # against pgmem; compare with the failure baseline
//! pgmem-conformance --update                # rewrite known_failures.txt and CONFORMANCE.md
//! pgmem-conformance --dsn "host=... user=postgres"           # strict: every record passes on PG
//! pgmem-conformance --dsn "host=... user=postgres" --record  # re-record expected results from PG
//! ```
//!
//! Positional arguments filter files by substring. `-v` prints every failure.

mod corpus;
mod runner;

use corpus::{Chunk, CorpusFile, Expect};
use runner::Target;
use std::collections::{BTreeMap, BTreeSet};
use std::path::PathBuf;
use std::process::ExitCode;

const BASELINE: &str = "known_failures.txt";

struct Args {
    dsn: Option<String>,
    record: bool,
    update: bool,
    verbose: bool,
    root: PathBuf,
    filters: Vec<String>,
}

fn parse_args() -> Result<Args, String> {
    let mut args = Args {
        dsn: None,
        record: false,
        update: false,
        verbose: false,
        root: PathBuf::from(concat!(env!("CARGO_MANIFEST_DIR"), "/../../conformance")),
        filters: Vec::new(),
    };
    let mut it = std::env::args().skip(1);
    while let Some(a) = it.next() {
        match a.as_str() {
            "--dsn" => args.dsn = Some(it.next().ok_or("--dsn needs a value")?),
            "--root" => args.root = PathBuf::from(it.next().ok_or("--root needs a value")?),
            "--record" => args.record = true,
            "--update" => args.update = true,
            "-v" | "--verbose" => args.verbose = true,
            s if s.starts_with('-') => return Err(format!("unknown option {s}")),
            _ => args.filters.push(a),
        }
    }
    if args.record && args.dsn.is_none() {
        return Err("--record needs --dsn: expected results come from real PostgreSQL".into());
    }
    if args.update && (args.dsn.is_some() || !args.filters.is_empty()) {
        return Err("--update runs the whole corpus against pgmem (no --dsn, no filters)".into());
    }
    Ok(args)
}

fn short(e: &Expect) -> String {
    let s = match e {
        Expect::Ok => "ok".to_owned(),
        Expect::Error { code, message } => format!("error {code} {}", message.as_deref().unwrap_or("")),
        Expect::Rows { columns, rows, .. } => format!("[{columns}] {}", rows.join("; ")),
    };
    if s.chars().count() > 400 { format!("{}…", s.chars().take(400).collect::<String>()) } else { s }
}

/// Per-record results of one file.
struct FileResult {
    name: String,
    area: String,
    total: usize,
    failures: Vec<(String, String)>,
}

#[derive(Default)]
struct Tally {
    total: usize,
    passed: usize,
}

fn rate(t: &Tally) -> String {
    if t.total == 0 { "—".into() } else { format!("{:.1}%", 100.0 * t.passed as f64 / t.total as f64) }
}

fn run(target: &Target, file: &mut CorpusFile, args: &Args) -> Result<FileResult, String> {
    let outcomes = runner::run_file(target, file)?;
    let mut failures = Vec::new();
    for (record, outcome) in file.records().zip(&outcomes) {
        if !outcome.passed {
            let first = record.sql.lines().next().unwrap_or("");
            if args.verbose || (args.dsn.is_some() && !args.record) {
                println!(
                    "FAIL {}:{}\n  {first}\n  expected: {}\n  actual:   {}",
                    file.name,
                    record.line,
                    short(&record.expect),
                    short(&outcome.actual)
                );
            }
            failures.push((record.key.clone(), first.to_owned()));
        }
    }
    let total = outcomes.len();
    if args.record {
        let mut outcomes = outcomes.into_iter();
        for chunk in &mut file.chunks {
            if let Chunk::Record(r) = chunk
                && let Some(o) = outcomes.next()
            {
                r.expect = match (o.actual, &r.expect) {
                    (Expect::Rows { columns, rows, .. }, Expect::Rows { sort, .. }) => Expect::Rows { sort: *sort, columns, rows },
                    (actual, _) => actual,
                };
            }
        }
        std::fs::write(&file.path, file.render()).map_err(|e| format!("{}: {e}", file.path.display()))?;
    }
    Ok(FileResult { name: file.name.clone(), area: file.area().to_owned(), total, failures })
}

fn report(results: &[FileResult]) -> String {
    let mut areas: BTreeMap<&str, Tally> = BTreeMap::new();
    let mut all = Tally::default();
    for r in results {
        let a = areas.entry(&r.area).or_default();
        a.total += r.total;
        a.passed += r.total - r.failures.len();
        all.total += r.total;
        all.passed += r.total - r.failures.len();
    }
    let mut out = String::from(
        "# Conformance\n\n<!-- Generated by `cargo run -p pgmem-conformance -- --update`; do not edit. -->\n\n\
         The corpus in [`conformance/`](conformance/) is SQL whose expected results were recorded from\n\
         PostgreSQL 18; CI re-verifies every record against PostgreSQL and runs it against pgmem.\n\
         A record passes when pgmem returns the same column names, column types and text values, or\n\
         the same SQLSTATE and error message.\n\n",
    );
    out.push_str(&format!("pgmem passes **{} / {} records ({})**.\n\n", all.passed, all.total, rate(&all)));
    out.push_str("| Area | Records | Pass | Rate |\n|---|---:|---:|---:|\n");
    for (area, t) in &areas {
        out.push_str(&format!("| {area} | {} | {} | {} |\n", t.total, t.passed, rate(t)));
    }
    out.push_str("\n## By file\n\n| File | Records | Pass | Rate |\n|---|---:|---:|---:|\n");
    for r in results {
        let t = Tally { total: r.total, passed: r.total - r.failures.len() };
        out.push_str(&format!("| {} | {} | {} | {} |\n", r.name, t.total, t.passed, rate(&t)));
    }
    out
}

fn baseline_text(results: &[FileResult]) -> String {
    let mut out = String::from(
        "# Corpus records pgmem fails today, by key (file:hash of the SQL); the first line of the SQL\n\
         # follows for reading. Regenerate with `cargo run -p pgmem-conformance -- --update`.\n",
    );
    for r in results {
        for (key, first) in &r.failures {
            out.push_str(&format!("{key}  # {first}\n"));
        }
    }
    out
}

/// Compares pgmem's failures with the committed baseline; true if they match.
fn check_baseline(args: &Args, results: &[FileResult]) -> Result<bool, String> {
    let path = args.root.join(BASELINE);
    let text = std::fs::read_to_string(&path).unwrap_or_default();
    let ran: BTreeSet<&str> = results.iter().map(|r| r.name.as_str()).collect();
    let known: BTreeSet<&str> = text
        .lines()
        .filter(|l| !l.starts_with('#') && !l.trim().is_empty())
        .filter_map(|l| l.split_whitespace().next())
        .filter(|k| k.rsplit_once(':').is_some_and(|(f, _)| ran.contains(f)))
        .collect();
    let failing: BTreeMap<&str, (&str, &str)> =
        results.iter().flat_map(|r| r.failures.iter().map(move |(k, first)| (k.as_str(), (r.name.as_str(), first.as_str())))).collect();
    let new: Vec<_> = failing.iter().filter(|(k, _)| !known.contains(*k)).collect();
    let fixed: Vec<_> = known.iter().filter(|k| !failing.contains_key(*k)).collect();
    for (k, (_, first)) in &new {
        println!("REGRESSION {k}: {first}");
    }
    for k in &fixed {
        println!("NOW PASSING {k}");
    }
    let mut ok = new.is_empty() && fixed.is_empty();
    if !new.is_empty() {
        println!("{} record(s) fail that the baseline expects to pass (run with -v for details)", new.len());
    }
    if !fixed.is_empty() {
        println!("{} record(s) now pass: run `cargo run -p pgmem-conformance -- --update` and commit", fixed.len());
    }
    if args.filters.is_empty() {
        let doc = args.root.join("../CONFORMANCE.md");
        if std::fs::read_to_string(&doc).unwrap_or_default() != report(results) {
            println!("CONFORMANCE.md is stale: run `cargo run -p pgmem-conformance -- --update`");
            ok = false;
        }
    }
    Ok(ok)
}

fn main_inner() -> Result<bool, String> {
    let args = parse_args()?;
    let target = args.dsn.clone().map_or(Target::Pgmem, Target::Postgres);
    let mut files = corpus::discover(&args.root)?;
    files.retain(|f| args.filters.is_empty() || args.filters.iter().any(|p| f.name.contains(p.as_str())));
    let mut results = Vec::new();
    for file in &mut files {
        results.push(run(&target, file, &args)?);
    }
    let total: usize = results.iter().map(|r| r.total).sum();
    let failed: usize = results.iter().map(|r| r.failures.len()).sum();
    let all = Tally { total, passed: total - failed };
    let label = if args.dsn.is_some() { "postgres" } else { "pgmem" };
    println!("{label}: {} / {} records pass ({}) in {} files", all.passed, all.total, rate(&all), results.len());
    if args.record {
        println!("recorded expected results from PostgreSQL");
        return Ok(true);
    }
    if args.dsn.is_some() {
        // The corpus must describe real PostgreSQL exactly.
        return Ok(failed == 0);
    }
    if args.update {
        std::fs::write(args.root.join(BASELINE), baseline_text(&results)).map_err(|e| e.to_string())?;
        std::fs::write(args.root.join("../CONFORMANCE.md"), report(&results)).map_err(|e| e.to_string())?;
        println!("wrote {BASELINE} and CONFORMANCE.md");
        return Ok(true);
    }
    check_baseline(&args, &results)
}

fn main() -> ExitCode {
    match main_inner() {
        Ok(true) => ExitCode::SUCCESS,
        Ok(false) => ExitCode::FAILURE,
        Err(e) => {
            eprintln!("pgmem-conformance: {e}");
            ExitCode::from(2)
        }
    }
}
