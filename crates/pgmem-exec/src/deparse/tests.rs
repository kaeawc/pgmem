#[test]
fn check_clause_without_wrapper() {
    let cat = catalog(PRODUCTS);
    let t = table(&cat, "products");
    let clause = |name: &str| {
        let c = t.constraints.iter().find(|c| c.name == name).expect("constraint");
        let ConstraintKind::Check { expr } = &c.kind else { panic!("not a check") };
        deparse_predicate(&cat, t, expr).expect("deparse")
    };
    assert_eq!(clause("c01"), "(price >= (0)::numeric)");
    assert_eq!(clause("c04"), "((status)::text = ANY ((ARRAY['a'::character varying, 'b'::character varying])::text[]))");
    assert_eq!(clause("c09"), "\nCASE\n    WHEN (a > 0) THEN (b > 0)\n    ELSE true\nEND");
}

