//! Every expected string here was recorded from PostgreSQL 18 running the same DDL
//! (`pg_get_expr`, `pg_get_constraintdef`, `pg_get_indexdef`, `pg_get_viewdef`).

use super::*;
use crate::session::{ServerClock, Session};
use pgmem_storage::Database;
use std::sync::Arc;

fn catalog(ddl: &str) -> Arc<Catalog> {
    let db = Arc::new(Database::new());
    let mut session = Session::new(Arc::clone(&db), Arc::new(ServerClock::default()), "postgres", "postgres", 1);
    for stmt in pgmem_parse::parse(ddl).expect("parse") {
        session.execute(&stmt, &[], &[]).unwrap_or_else(|e| panic!("{ddl}: {}", e.message));
    }
    Arc::clone(&db.current().catalog)
}

fn table<'a>(cat: &'a Catalog, name: &str) -> &'a TableDef {
    cat.table(name).unwrap_or_else(|| panic!("no table {name}"))
}

/// Compares every case and reports all mismatches at once.
fn check_all(what: &str, cases: &[(&str, &str)], actual: impl Fn(&str) -> Option<String>) {
    let mut failures = Vec::new();
    for (name, expected) in cases {
        let got = actual(name);
        if got.as_deref() != Some(*expected) {
            failures.push(format!("{what} {name}:\n  expected: {expected:?}\n  got:      {got:?}"));
        }
    }
    assert!(failures.is_empty(), "{} mismatches:\n{}", failures.len(), failures.join("\n"));
}

fn check_defaults(ddl: &str, tname: &str, cases: &[(&str, &str)]) {
    let cat = catalog(ddl);
    let t = table(&cat, tname);
    check_all("default", cases, |col| {
        let c = t.column(col)?;
        deparse_default(&cat, t, c).expect("deparse")
    });
}

fn check_constraints(ddl: &str, tname: &str, cases: &[(&str, &str)]) {
    let cat = catalog(ddl);
    let t = table(&cat, tname);
    check_all("constraint", cases, |name| {
        let c = t.constraints.iter().find(|c| c.name == name)?;
        Some(deparse_constraint(&cat, t, c).expect("deparse"))
    });
}

fn check_views(ddl: &str, cases: &[(&str, &str)]) {
    let cat = catalog(ddl);
    check_all("view", cases, |name| Some(deparse_view(&cat, cat.view(name)?).expect("deparse")));
}

fn check_indexes(ddl: &str, tname: &str, cases: &[(&str, &str)]) {
    let cat = catalog(ddl);
    let t = table(&cat, tname);
    check_all("index", cases, |name| {
        let i = t.indexes.iter().find(|i| i.name == name)?;
        Some(deparse_index(&cat, t, i).expect("deparse"))
    });
}

