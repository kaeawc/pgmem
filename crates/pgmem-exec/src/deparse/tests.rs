#[test]
fn defaults_postgres_does_not_store() {
    let cat =
        catalog("CREATE TABLE t (a text DEFAULT NULL, b integer DEFAULT NULL::integer, c bigint GENERATED BY DEFAULT AS IDENTITY, d int)");
    let t = table(&cat, "t");
    for col in ["a", "b", "c", "d"] {
        assert_eq!(deparse_default(&cat, t, t.column(col).expect("column")).expect("deparse"), None, "{col}");
    }
}

