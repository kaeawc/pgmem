/// Expressions the deparser cannot model exactly still produce text (never a panic).
#[test]
fn approximations_do_not_fail() {
    let cat = catalog("CREATE TABLE t (a int, b text, c timestamptz, arr int[])");
    let t = table(&cat, "t");
    let exprs = [
        "(a, b) = (1, 'x')",
        "no_such_function(a, 'x')",
        "missing_column + 1",
        "$1 + a",
        "a = ANY (SELECT 1)",
        "b COLLATE \"C\"",
        "c AT TIME ZONE 'UTC'",
        "arr[1:2]",
        "'x'::no_such_type",
        "ARRAY(SELECT 1)",
        "b SIMILAR TO 'x' ESCAPE '#'",
    ];
    for e in exprs {
        let stmt = pgmem_parse::parse_one(&format!("SELECT {e}")).expect("parse");
        let ir::Statement::Query(q) = stmt else { panic!("not a query") };
        let ir::SetExpr::Select(s) = &q.body else { panic!("not a select") };
        let ir::SelectItem::Expr { expr, .. } = &s.projection[0] else { panic!("not an expression") };
        let out = deparse_expr(&cat, t, expr).expect("deparse");
        assert!(!out.is_empty(), "{e}");
    }
    let cases =
        [("a = ANY (SELECT 1)", "(a IN ( SELECT 1))"), ("c AT TIME ZONE 'UTC'", "(c AT TIME ZONE 'UTC'::text)"), ("arr[1:2]", "arr[1:2]")];
    for (e, expected) in cases {
        let ir::Statement::Query(q) = pgmem_parse::parse_one(&format!("SELECT {e}")).expect("parse") else { panic!() };
        let ir::SetExpr::Select(s) = &q.body else { panic!() };
        let ir::SelectItem::Expr { expr, .. } = &s.projection[0] else { panic!() };
        assert_eq!(deparse_expr(&cat, t, expr).expect("deparse"), expected);
    }
}
