//! Sequence parameters (AS, MIN/MAXVALUE, CYCLE, CACHE, OWNED BY) and ALTER SEQUENCE, reading
//! a sequence as a relation, identity column options and ALTER ... IDENTITY, OVERRIDING USER
//! VALUE, generated column rules (immutability, dependencies, SET / DROP EXPRESSION).

use crate::support::{expect_code, message, setup, texts};

fn rows(c: &mut postgres::Client, sql: &str) -> Vec<Vec<String>> {
    texts(c, sql).into_iter().map(|r| r.into_iter().map(|v| v.unwrap_or_else(|| "NULL".into())).collect()).collect()
}

#[test]
fn sequence_parameters_and_alter() {
    let (_db, mut c) = setup();
    c.batch_execute(
        "CREATE SEQUENCE small MINVALUE 1 MAXVALUE 3; CREATE SEQUENCE cyc MAXVALUE 2 CYCLE; CREATE SEQUENCE down INCREMENT BY -1;
         CREATE SEQUENCE si AS smallint START 32767",
    )
    .expect("setup");
    assert_eq!(
        rows(
            &mut c,
            "SELECT nextval('small'), nextval('small'), nextval('small'), nextval('cyc'), nextval('cyc'), nextval('cyc'), nextval('down'), nextval('si')"
        ),
        [["1", "2", "3", "1", "2", "1", "-1", "32767"]]
    );
    let e = expect_code(c.batch_execute("SELECT nextval('small')"), "2200H");
    assert_eq!(message(&e), "nextval: reached maximum value of sequence \"small\" (3)");
    let e = expect_code(c.batch_execute("SELECT nextval('si')"), "2200H");
    assert_eq!(message(&e), "nextval: reached maximum value of sequence \"si\" (32767)");
    for (sql, msg) in [
        ("CREATE SEQUENCE bad START WITH 0 MINVALUE 1", "START value (0) cannot be less than MINVALUE (1)"),
        ("CREATE SEQUENCE bad MINVALUE 5 MAXVALUE 5", "MINVALUE (5) must be less than MAXVALUE (5)"),
        ("CREATE SEQUENCE bad AS smallint MAXVALUE 40000", "MAXVALUE (40000) is out of range for sequence data type smallint"),
        ("CREATE SEQUENCE bad AS text", "sequence type must be smallint, integer, or bigint"),
        ("CREATE SEQUENCE bad CACHE 0", "CACHE (0) must be greater than zero"),
    ] {
        let e = expect_code(c.batch_execute(sql), "22023");
        assert_eq!(message(&e), msg, "{sql}");
    }
    assert_eq!(rows(&mut c, "SELECT last_value, is_called FROM small"), [["3", "t"]]);
    c.batch_execute("CREATE SEQUENCE s2 START WITH 100 INCREMENT BY 10; ALTER SEQUENCE s2 RESTART WITH 5").expect("restart");
    assert_eq!(rows(&mut c, "SELECT last_value, is_called FROM s2"), [["5", "f"]]);
    assert_eq!(rows(&mut c, "SELECT nextval('s2')"), [["5"]]);
    c.batch_execute("ALTER SEQUENCE s2 INCREMENT BY 2").expect("increment");
    assert_eq!(rows(&mut c, "SELECT nextval('s2')"), [["7"]]);
    c.batch_execute("ALTER SEQUENCE s2 RESTART; ALTER SEQUENCE s2 RENAME TO s2b").expect("restart, rename");
    assert_eq!(rows(&mut c, "SELECT nextval('s2b')"), [["100"]]);
    expect_code(c.batch_execute("ALTER SEQUENCE nosuch RESTART"), "42P01");
    c.batch_execute("ALTER SEQUENCE IF EXISTS nosuch RESTART").expect("IF EXISTS");
    // A renamed sequence keeps feeding the defaults that use it.
    c.batch_execute("CREATE TABLE ser (id serial, v text); ALTER SEQUENCE ser_id_seq RENAME TO ser_ids; INSERT INTO ser (v) VALUES ('a')")
        .expect("rename a serial's sequence");
    assert_eq!(rows(&mut c, "SELECT id FROM ser"), [["1"]]);
    assert_eq!(
        rows(
            &mut c,
            "SELECT sequence_name, data_type, maximum_value, cycle_option FROM information_schema.sequences WHERE sequence_name IN ('cyc', 'si', 'small') ORDER BY 1"
        ),
        [["cyc", "bigint", "2", "YES"], ["si", "smallint", "32767", "NO"], ["small", "bigint", "3", "NO"]]
    );
    // OWNED BY: dropped with its table.
    c.batch_execute("CREATE TABLE owner_t (id int); CREATE SEQUENCE owned_seq OWNED BY owner_t.id; DROP TABLE owner_t").expect("OWNED BY");
    expect_code(c.batch_execute("SELECT nextval('owned_seq')"), "42P01");
}

#[test]
fn identity_columns() {
    let (_db, mut c) = setup();
    c.batch_execute(
        "CREATE TABLE idd (id bigint GENERATED BY DEFAULT AS IDENTITY, v text);
         CREATE TABLE idopt (id int GENERATED ALWAYS AS IDENTITY (START WITH 1000 INCREMENT BY 5), v text);
         INSERT INTO idd (v) VALUES ('a'); INSERT INTO idd (id, v) OVERRIDING USER VALUE VALUES (999, 'b');
         INSERT INTO idopt (v) VALUES ('a'), ('b')",
    )
    .expect("setup");
    assert_eq!(rows(&mut c, "SELECT id, v FROM idd ORDER BY v"), [["1", "a"], ["2", "b"]]);
    assert_eq!(rows(&mut c, "SELECT id FROM idopt ORDER BY id"), [["1000"], ["1005"]]);
    assert_eq!(
        rows(
            &mut c,
            "SELECT identity_generation, identity_start, identity_increment FROM information_schema.columns WHERE table_name = 'idopt' AND column_name = 'id'"
        ),
        [["ALWAYS", "1000", "5"]]
    );
    let e = expect_code(c.batch_execute("CREATE TABLE badid (id text GENERATED ALWAYS AS IDENTITY)"), "22023");
    assert_eq!(message(&e), "identity column type must be smallint, integer, or bigint");
    c.batch_execute("ALTER TABLE idd ALTER COLUMN id SET GENERATED ALWAYS").expect("SET GENERATED");
    expect_code(c.batch_execute("INSERT INTO idd (id, v) VALUES (1, 'z')"), "428C9");
    c.batch_execute("ALTER TABLE idd ALTER COLUMN id RESTART WITH 500").expect("RESTART");
    assert_eq!(rows(&mut c, "INSERT INTO idd (v) VALUES ('r') RETURNING id"), [["500"]]);
    c.batch_execute("ALTER TABLE idd ALTER COLUMN id SET INCREMENT BY 10").expect("SET INCREMENT");
    assert_eq!(rows(&mut c, "INSERT INTO idd (v) VALUES ('s') RETURNING id"), [["510"]]);
    c.batch_execute("ALTER TABLE idd ALTER COLUMN id DROP IDENTITY").expect("DROP IDENTITY");
    expect_code(c.batch_execute("INSERT INTO idd (v) VALUES ('noid')"), "23502");
    let e = expect_code(c.batch_execute("ALTER TABLE idd ALTER COLUMN id DROP IDENTITY"), "55000");
    assert_eq!(message(&e), "column \"id\" of relation \"idd\" is not an identity column");
    c.batch_execute("ALTER TABLE idd ALTER COLUMN id DROP IDENTITY IF EXISTS").expect("IF EXISTS");
    let e = expect_code(
        c.batch_execute("CREATE TABLE nn (id int, v text); ALTER TABLE nn ALTER COLUMN id ADD GENERATED ALWAYS AS IDENTITY"),
        "55000",
    );
    assert_eq!(message(&e), "column \"id\" of relation \"nn\" must be declared NOT NULL before identity can be added");
    c.batch_execute(
        "CREATE TABLE addid (id int NOT NULL, v text); ALTER TABLE addid ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY;
         INSERT INTO addid (v) VALUES ('x'); ALTER TABLE addid ADD COLUMN id2 int GENERATED ALWAYS AS IDENTITY",
    )
    .expect("ADD GENERATED");
    assert_eq!(rows(&mut c, "SELECT id, id2, v FROM addid"), [["1", "1", "x"]]);
}

#[test]
fn generated_column_rules() {
    let (_db, mut c) = setup();
    c.batch_execute(
        "CREATE TABLE people (first text, last text, full_name text GENERATED ALWAYS AS (first || ' ' || last) STORED);
         INSERT INTO people (first, last) VALUES ('Ada', 'Lovelace')",
    )
    .expect("setup");
    let e = expect_code(
        c.batch_execute("CREATE TABLE bad (a int, b int GENERATED ALWAYS AS (a * 2) STORED, c int GENERATED ALWAYS AS (b * 2) STORED)"),
        "42P17",
    );
    assert_eq!(message(&e), "cannot use generated column \"b\" in column generation expression");
    let e = expect_code(c.batch_execute("CREATE TABLE bad (a timestamptz GENERATED ALWAYS AS (now()) STORED)"), "42P17");
    assert_eq!(message(&e), "generation expression is not immutable");
    // Postgres 18's VIRTUAL (also the default) reads the same values.
    c.batch_execute("CREATE TABLE virt (a int, b int GENERATED ALWAYS AS (a + 1) VIRTUAL, c int GENERATED ALWAYS AS (a * 10)); INSERT INTO virt (a) VALUES (1)")
        .expect("virtual");
    assert_eq!(rows(&mut c, "SELECT a, b, c FROM virt"), [["1", "2", "10"]]);
    c.batch_execute(
        "CREATE TABLE ext (x int); INSERT INTO ext VALUES (3), (4); ALTER TABLE ext ADD COLUMN sq int GENERATED ALWAYS AS (x * x) STORED",
    )
    .expect("ADD COLUMN generated");
    assert_eq!(rows(&mut c, "SELECT x, sq FROM ext ORDER BY x"), [["3", "9"], ["4", "16"]]);
    c.batch_execute("ALTER TABLE ext ALTER COLUMN sq DROP EXPRESSION; INSERT INTO ext VALUES (5, 0)").expect("DROP EXPRESSION");
    assert_eq!(rows(&mut c, "SELECT x, sq FROM ext ORDER BY x"), [["3", "9"], ["4", "16"], ["5", "0"]]);
    c.batch_execute("ALTER TABLE people ALTER COLUMN full_name SET EXPRESSION AS (last || ', ' || first)").expect("SET EXPRESSION");
    assert_eq!(rows(&mut c, "SELECT full_name FROM people"), [["Lovelace, Ada"]]);
    let e = expect_code(c.batch_execute("ALTER TABLE people DROP COLUMN first"), "2BP01");
    assert_eq!(message(&e), "cannot drop column first of table people because other objects depend on it");
    c.batch_execute("ALTER TABLE people DROP COLUMN first CASCADE").expect("CASCADE");
    assert_eq!(
        rows(&mut c, "SELECT column_name FROM information_schema.columns WHERE table_name = 'people' ORDER BY ordinal_position"),
        [["last"]]
    );
}
